let s = "Hey there!"; // String literal
console.log(s); // Output: Hey there!

s+= " How are you?"; // Concatenation using += operator
console.log(s); // Output: Hey there! How are you?


//concatenation can also be done using below methods

console.log("Hello, " + "world!"); // Output: Hello, world!
console.log("Hello","world!"); // Output: Hello world!
console.log(1,2,3,4,"hello","ram"); // Output: 1 2 3 4 "hello" "ram"