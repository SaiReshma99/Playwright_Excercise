let x = 5;
x = "reshma";
console.log(x); // Output: reshma
// the latest one will be assigned to the variable x, which is "reshma" in this case. The previous value of x, which was 5, will be overwritten by the new value.


let y = 10;
y += 5; // equivalent to y = y + 5
console.log(y); // Output: 15

//the above example demonstrates the use of the assignment operator +=, which adds the value on the right (5) to the current value of y (10) and assigns the result back to y. The final value of y is 15.