// && (logical AND)
// || (logical OR)
// ! (logical NOT)

let a = true;
let b = false;
console.log("a && b:", a && b); // Output: false (both a and b must be true for the result to be true)
console.log("a || b:", a || b); // Output: true (either a or b must be true for the result to be true)
console.log("!a:", !a); // Output: false (negates the value of a, which is true, so the result is false)    