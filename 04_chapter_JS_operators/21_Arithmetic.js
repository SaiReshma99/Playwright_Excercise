//assignment operator
a=2;
b=3;

//arithmetic operators  

let sum = a + b; // addition
let difference = a - b; // subtraction
let product = a * b; // multiplication
let quotient = a / b;   // division
let remainder = a % b; // modulus   

console.log("sum:", sum); // Output: 5
console.log("difference:", difference); // Output: -1           
console.log("product:", product); // Output: 6
console.log("quotient:", quotient); // Output: 0.6666666666666666
console.log("remainder:", remainder); // Output: 2      

//exponentiation operator
let exponentiation = a ** b;    
console.log("exponentiation:", exponentiation); // Output: 8

