//decimal literal
let decimalLiteral = 34; //34 is a decimal literal value assigned to the variable decimalLiteral
//binary literal
let binaryLiteral = 0b1010; //0b1010 is a binary literal value assigned to the variable binaryLiteral       

//octal literal is a base-8 number system that uses digits from 0 to 7. In JavaScript, octal literals are represented by prefixing the number with "0o" or "0O". For example, the octal literal 0o77 represents the decimal value 63.
let octalLiteral = 0o77; //0o77 is an octal literal value assigned to the variable octalLiteral
//hexadecimal literal is a base-16 number system that uses digits from 0 to 9 and letters A to F (or a to f) to represent values. In JavaScript, hexadecimal literals are represented by prefixing the number with "0x" or "0X". For example, the hexadecimal literal 0xFF represents the decimal value 255.
let hexadecimalLiteral = 0xFF; //0xFF is a hexadecimal literal value assigned to the variable hexadecimalLiteral        

//floating-point literal is a numeric literal that represents a decimal number with a fractional part. In JavaScript, floating-point literals are represented using a decimal point (.) to separate the whole number part from the fractional part. For example, the floating-point literal 3.14 represents the value of pi.
let floatingPointLiteral = 3.14; //3.14 is a floating-point literal value assigned to the variable floatingPointLiteral     
let negativeLiteral = -10; //-10 is a negative literal value assigned to the variable negativeLiteral

console.log(decimalLiteral); // Output: 34
console.log(binaryLiteral); // Output: 10                   
console.log(octalLiteral); // Output: 63
console.log(hexadecimalLiteral); // Output: 255
console.log(floatingPointLiteral); // Output: 3.14
console.log(negativeLiteral); // Output: -10


//exponential literal is a numeric literal that represents a number in scientific notation. In JavaScript, exponential literals are represented using the letter "e" or "E" followed by an exponent value. For example, the exponential literal 1.5e3 represents the value 1500 (1.5 multiplied by 10 raised to the power of 3).
let exponentialLiteral = 1.5e3; //1.5e3 is an exponential literal value assigned to the variable exponentialLiteral
console.log(exponentialLiteral); // Output: 1500

