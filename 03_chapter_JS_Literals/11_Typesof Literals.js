let age = 25; //25 is a literal value assigned to the variable age  
let name = "Reshma"; // "Reshma" is a literal value assigned to the variable name   
let name2 = 'Reshma'; // 'Reshma' is a literal value assigned to the variable name2 
let pi = 3.14; //3.14 is a literal value assigned to the variable pi        
let result = true; //true is a literal value assigned to the variable result    
let nullValue = null; //null is a literal value assigned to the variable nullValue  
let undefinedValue; 
let arr = [1, 2, 3]; // [1, 2, 3] is a literal value assigned to the variable arr   
let obj = { name: "Reshma", age: 25 }; // { name: "Reshma", age: 25 } is a literal value assigned to the variable obj


console.log(age); // Output: 25
console.log(name);  // Output: Reshma
console.log(name2); // Output: Reshma
console.log(pi);    // Output: 3.14
console.log(result); // Output: true
console.log(nullValue); // Output: null
console.log(undefinedValue); // Output: undefined
console.log(arr);   // Output: [1, 2, 3]
console.log(obj);   // Output: { name: "Reshma", age: 25 }


console.log(typeof age); // Output: number
console.log(typeof name);  // Output: string
console.log(typeof name2); // Output: string
console.log(typeof pi);             // Output: number
console.log(typeof result); // Output: boolean
console.log(typeof nullValue); // Output: object (this is a known quirk in JavaScript, null is considered an object)
console.log(typeof undefinedValue); // Output: undefined
console.log(typeof arr);   // Output: object (arrays are considered objects in JavaScript)
console.log(typeof obj);   // Output: object                
