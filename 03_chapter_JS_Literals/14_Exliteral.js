let a = 100; //100 is a literal value assigned to the variable a
let b = -10; //-10 is a literal value assigned to the variable b
let c = 3.14; //3.14 is a literal value assigned to the variable c  


let hx = 0xFF; //0xFF is a hexadecimal literal value assigned to the variable hx
let bin = 0b1010; //0b1010 is a binary literal value assigned to the variable bin               
let oct = 0o77; //0o77 is an octal literal value assigned to the variable oct   


console.log(a); // Output: 100  
console.log(b); // Output: -10
console.log(c); // Output: 3.14
console.log(hx); // Output: 255             
console.log(bin); // Output: 10
console.log(oct); // Output: 63     


console.log(typeof a); // Output: number        
console.log(typeof b); // Output: number
console.log(typeof c); // Output: number
console.log(typeof hx); // Output: number       
console.log(typeof bin); // Output: number
console.log(typeof oct); // Output: number      